import java.util.*;
public class Of_Given_5_Numbers_How_Many_Are_Even {
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        int n1=sc.nextInt();
        int n2=sc.nextInt();
        int n3=sc.nextInt();
        int n4=sc.nextInt();
        int n5=sc.nextInt();
        if(n1%2==0) System.out.println(n1+" is even");
        if(n2%2==0) System.out.println(n2+" is even");
        if(n3%2==0) System.out.println(n3+" is even");
        if(n4%2==0) System.out.println(n4+" is even");
        if(n5%2==0) System.out.println(n5+" is even");
    }
}
